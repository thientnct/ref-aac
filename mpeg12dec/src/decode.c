void decodeFrameData(decData *dd)
{
  frameData *fd = &dd->frameData;
  
  /* calc crc if needed */
  if (fd->error_protection)
  {
    dd->newCRC = 0xffff;
    updateCRC(fd->bitrate_index,       4, &dd->newCRC);
    updateCRC(fd->sampling_frequency,  2, &dd->newCRC);
    updateCRC(fd->padding,             1, &dd->newCRC);
    updateCRC(fd->extension,           1, &dd->newCRC);
    updateCRC(fd->mode,                2, &dd->newCRC);
    updateCRC(fd->mode_ext,            2, &dd->newCRC);
    updateCRC(fd->copyright,           1, &dd->newCRC);
    updateCRC(fd->original,            1, &dd->newCRC);
    updateCRC(fd->emphasis,            2, &dd->newCRC);
  }

  if (fd->lay == LAYER2)
    dd->sblimit = pickTable(dd);
  else 
    dd->sblimit = SBLIMIT;

  if(fd->mode == MPG_MD_JOINT_STEREO)
    dd->jsbound = jsb_table[fd->lay-1][fd->mode_ext];
  else
    dd->jsbound = dd->sblimit;

}

int I_CRC_calc( decData *dd, unsigned int bit_alloc[2][SBLIMIT])
{
  int i, k;
  int stereo  = dd->frameData.channels;
  int jsbound = dd->jsbound;

  for (i=0;i<SBLIMIT;i++)
    for (k=0;k<((i<jsbound)?stereo:1);k++)
      updateCRC(bit_alloc[k][i], 4, &dd->newCRC);

  return (dd->frameData.crc != dd->newCRC);
}

int II_CRC_calc(
                 decData *dd,
                 unsigned int bit_alloc[2][SBLIMIT],
                 unsigned int scfsi[2][SBLIMIT] )
{
  int i, k;
  int stereo  = dd->frameData.channels;
  int sblimit = dd->sblimit;
  int jsbound = dd->jsbound;
  al_table *alloc = &dd->tableAlloc;

  for (i=0;i<sblimit;i++)
    for (k=0;k<((i<jsbound)?stereo:1);k++)
      updateCRC(bit_alloc[k][i], (*alloc)[i][0].bits, &dd->newCRC);

  for (i=0;i<sblimit;i++)
    for (k=0;k<stereo;k++)
      if (bit_alloc[k][i])
        updateCRC(scfsi[k][i], 2, &dd->newCRC);

  return (dd->frameData.crc != dd->newCRC);
}





