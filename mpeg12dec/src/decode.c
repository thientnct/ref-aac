static
void updateCRC(unsigned int data, unsigned int length, unsigned int *crc )
{
  unsigned int  masking, carry;

  masking = 1 << length;

  while((masking >>= 1)){
    carry = *crc & 0x8000;
    *crc <<= 1;
    if (!carry ^ !(data & masking))
    *crc ^= CRC16_POLYNOMIAL;
  }
  *crc &= 0xffff;
}

/**
 * Read N bits from the bitBuffer and update the CRC 
 */
static
unsigned int getBitsCRC(HANDLE_bitBuffer buf, int N, unsigned int *crc)
{
  unsigned long bits;
  bitBufferRead(buf, &bits, N);
  updateCRC(bits, N, crc);
  return bits;
}

/**
 * Using the decoded info the appropriate possible quantization per subband 
 * table is loaded - choose table, load if necess, return # sb's 
 */
static
int pickTable(decData *dd)
{
  int table;
  int sblim = dd->sblimit; /* return current value if no load */
  int br_per_ch = dd->frameData.bitrate / dd->frameData.channels; 
  int sfrq = (int)dd->frameData.sfreq;

  /* decision rules refer to per-channel bitrates (kbits/sec/chan) */
  if (dd->frameData.version == MPEG_PHASE1) 
  { /* MPEG-1 */
    if ((sfrq == 48 && (br_per_ch == 0 || br_per_ch >= 56)) || (br_per_ch >= 56 && br_per_ch <= 80)) 
      table = 0;
    else if (sfrq != 48 && (br_per_ch == 0 || br_per_ch >= 96)) 
      table = 1;
    else if (sfrq != 32 && br_per_ch <= 48) 
      table = 2;
    else table = 3;
  }
  else 
  { /* MPEG-2 LSF & MPEG_2_5 */
    table = 4;
  }

  if (dd->tableNumber != table) 
  {
    dd->tableNumber = table; 
    sblim = get_bit_alloc(table, &dd->tableAlloc);
  }
  return sblim;
}


