void III_M_S(
             double xr[2][SBLIMIT][SSLIMIT],
             double lr[2][SBLIMIT][SSLIMIT],
             int Start,
             int Number )
{
    int sb, ss;
    int i;

    for (i = Start; i < (Start + Number); i++) {
        sb = i / 18; ss = i % 18;
        lr[0][sb][ss] = (xr[0][sb][ss]+xr[1][sb][ss])/(double)1.41421356;  /* Sum */
        lr[1][sb][ss] = (xr[0][sb][ss]-xr[1][sb][ss])/(double)1.41421356;  /* Diff */
    }
}

void III_Intensity(
                   double xr[2][SBLIMIT][SSLIMIT],
                   double lr[2][SBLIMIT][SSLIMIT],
                   double IntensFactor[2][SBLIMIT*SSLIMIT],
                   int Start,
                   int Number )
{
    int sb, ss;
    int i;

    for (i = Start; i < (Start + Number); i++) {
        sb = i / 18; ss = i % 18;                 /* start values for (lr[0], xr[0]), (lr[1], xr[1]) */
        lr[0][sb][ss] = xr[0][sb][ss] * IntensFactor[0][i];
        lr[1][sb][ss] = xr[0][sb][ss] * IntensFactor[1][i];
    }
}
