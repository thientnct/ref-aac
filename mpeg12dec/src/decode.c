/* create in synthesis filter */
void createSynFilter (synData *syn)
{
    int i,k;

    for (i=0; i<64; i++)
        for (k=0; k<32; k++) 
        {
            if ((syn->filter[i][k] = 1e9*cos((double)((PI64*i+PI4)*(2*k+1)))) >= 0)
                modf(syn->filter[i][k]+0.5, &syn->filter[i][k]);
            else
                modf(syn->filter[i][k]-0.5, &syn->filter[i][k]);
            syn->filter[i][k] *= 1e-9;
        }
}

