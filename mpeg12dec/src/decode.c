int III_get_side_info_crc(
                             HANDLE_bitBuffer inputBitBuffer,
                             III_side_info_t *si,
                             decData *dd)

/* get side info and calculate CRC at the same time / adapted by efs 2003-11-11 */
{
    
    int ch, gr, i;

    int stereo  = dd->frameData.channels;

    if (dd->frameData.version == MPEG_PHASE1) /* MPEG1 */
    { 
        si->main_data_begin = getBitsCRC(inputBitBuffer, 9, &dd->newCRC);
        if (stereo == 1) {
          si->private_bits = getBitsCRC(inputBitBuffer,5, &dd->newCRC);
        }
        else {
          si->private_bits = getBitsCRC(inputBitBuffer,3, &dd->newCRC);
        }

        for (ch=0; ch<stereo; ch++)
            for (i=0; i<4; i++)
                si->ch[ch].scfsi[i] = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);


            for (gr=0; gr< 2 ; gr++) {
                for (ch=0; ch<stereo; ch++) {
                    si->ch[ch].gr[gr].part2_3_length = getBitsCRC(inputBitBuffer, 12, &dd->newCRC);
                    si->ch[ch].gr[gr].big_values = getBitsCRC(inputBitBuffer, 9, &dd->newCRC);
                    si->ch[ch].gr[gr].global_gain = getBitsCRC(inputBitBuffer, 8, &dd->newCRC);
                    si->ch[ch].gr[gr].scalefac_compress = getBitsCRC(inputBitBuffer, 4, &dd->newCRC);
                    si->ch[ch].gr[gr].window_switching_flag = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                    if (si->ch[ch].gr[gr].window_switching_flag) {
                        si->ch[ch].gr[gr].block_type = getBitsCRC(inputBitBuffer, 2, &dd->newCRC);
                        si->ch[ch].gr[gr].mixed_block_flag = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                        for (i=0; i<2; i++) {
                            si->ch[ch].gr[gr].table_select[i] = getBitsCRC(inputBitBuffer, 5, &dd->newCRC);
                        }
                        for (i=0; i<3; i++) {
                            si->ch[ch].gr[gr].subblock_gain[i] = getBitsCRC(inputBitBuffer, 3, &dd->newCRC);
                        }

                        /* Set region_count parameters since they are implicit in this case. */

                        if (si->ch[ch].gr[gr].block_type == 0) {
                            printf("Side info bad: block_type == 0 in split block.\n");
                           return 0;
                        }
                        else if (si->ch[ch].gr[gr].block_type == 2
                            && si->ch[ch].gr[gr].mixed_block_flag == 0)
                        {
                          si->ch[ch].gr[gr].region0_count = 8; /* MI 9; */
                        }
                        else si->ch[ch].gr[gr].region0_count = 7; /* MI 8; */
                        si->ch[ch].gr[gr].region1_count = 20 -
                            si->ch[ch].gr[gr].region0_count;
                    }
                    else {
                        for (i=0; i<3; i++){
                            si->ch[ch].gr[gr].table_select[i] = getBitsCRC(inputBitBuffer, 5, &dd->newCRC);
                        }
                        si->ch[ch].gr[gr].region0_count = getBitsCRC(inputBitBuffer, 4, &dd->newCRC);
                        si->ch[ch].gr[gr].region1_count = getBitsCRC(inputBitBuffer, 3, &dd->newCRC);
                        si->ch[ch].gr[gr].block_type = 0;
                    }
                    si->ch[ch].gr[gr].preflag = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                    si->ch[ch].gr[gr].scalefac_scale = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                    si->ch[ch].gr[gr].count1table_select = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                }
            }
    }
    else /* Layer 3 LSF */
    {
        si->main_data_begin = getBitsCRC(inputBitBuffer, 8, &dd->newCRC);
        if (stereo == 1) {
            si->private_bits = getBitsCRC(inputBitBuffer,1, &dd->newCRC);
        }
        else si->private_bits = getBitsCRC(inputBitBuffer,2, &dd->newCRC);

        for (gr=0; gr< 1 ; gr++) {
            for (ch=0; ch<stereo; ch++) {
                si->ch[ch].gr[gr].part2_3_length = getBitsCRC(inputBitBuffer, 12, &dd->newCRC);
                si->ch[ch].gr[gr].big_values = getBitsCRC(inputBitBuffer, 9, &dd->newCRC);
                si->ch[ch].gr[gr].global_gain = getBitsCRC(inputBitBuffer, 8, &dd->newCRC);
                si->ch[ch].gr[gr].scalefac_compress = getBitsCRC(inputBitBuffer, 9, &dd->newCRC);   
                si->ch[ch].gr[gr].window_switching_flag = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);

                if (si->ch[ch].gr[gr].window_switching_flag) {
                
                    si->ch[ch].gr[gr].block_type = getBitsCRC(inputBitBuffer, 2, &dd->newCRC);
                    si->ch[ch].gr[gr].mixed_block_flag = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                    for (i=0; i<2; i++) {
                        si->ch[ch].gr[gr].table_select[i] = getBitsCRC(inputBitBuffer, 5, &dd->newCRC);
                    }
                    si->ch[ch].gr[gr].table_select[2] = 0; /* not used, set to zero */

                    for (i=0; i<3; i++) {
                        si->ch[ch].gr[gr].subblock_gain[i] = getBitsCRC(inputBitBuffer, 3, &dd->newCRC);
                    }

                    /* Set region_count parameters since they are implicit in this case. */

                    if (si->ch[ch].gr[gr].block_type == 0) {
                        printf("Side info bad: block_type == 0 in split block.\n");
                        return 0;
                    }
                    else if (si->ch[ch].gr[gr].block_type == 2 && si->ch[ch].gr[gr].mixed_block_flag == 0)
                    {
                        si->ch[ch].gr[gr].region0_count = 8; /* MI 9; */
                    }
                    else
                    {
                        si->ch[ch].gr[gr].region0_count = 7; /* MI 8; */
                    }
                    si->ch[ch].gr[gr].region1_count = 20 - si->ch[ch].gr[gr].region0_count;

                }
                else {
                    for (i=0; i<3; i++) {
                        si->ch[ch].gr[gr].table_select[i] = getBitsCRC(inputBitBuffer, 5, &dd->newCRC);
                    }
                    si->ch[ch].gr[gr].region0_count = getBitsCRC(inputBitBuffer, 4, &dd->newCRC);
                    si->ch[ch].gr[gr].region1_count = getBitsCRC(inputBitBuffer, 3, &dd->newCRC);
                    si->ch[ch].gr[gr].block_type = 0;
                }

                si->ch[ch].gr[gr].scalefac_scale = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
                si->ch[ch].gr[gr].count1table_select = getBitsCRC(inputBitBuffer, 1, &dd->newCRC);
            }
        }
    }
    return 1;
}


