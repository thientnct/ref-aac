double Ci[8]={-0.6,-0.535,-0.33,-0.185,-0.095,-0.041,-0.0142,-0.0037};

void III_antialias_init(antialiasData *aa)
{
    int i;
    double sq;
    for (i=0;i<8;i++) 
    {
        sq=sqrt(1.0+Ci[i]*Ci[i]);
        aa->cs[i] = 1.0/sq;
        aa->ca[i] = Ci[i]/sq;
    }
}

void III_antialias(
                   double xr[SBLIMIT][SSLIMIT],
                   double hybridIn[SBLIMIT][SSLIMIT],
                   struct gr_info_s *gr_info,
                   int antialias_mixed_blocks,
                   antialiasData *aa)
{
    double        bu,bd;  /* upper and lower butterfly inputs */
    int           ss,sb,sblim;

    /* clear all inputs */

    for(sb=0;sb<SBLIMIT;sb++)
        for(ss=0;ss<SSLIMIT;ss++)
            hybridIn[sb][ss] = xr[sb][ss];

    if  (gr_info->window_switching_flag && (gr_info->block_type == 2) &&
         !gr_info->mixed_block_flag ) return;

    if ( gr_info->window_switching_flag && gr_info->mixed_block_flag &&
         (gr_info->block_type == 2))
      sblim = (antialias_mixed_blocks?1:0);
    else
      sblim = SBLIMIT-1;

    /* 31 alias-reduction operations between each pair of sub-bands */
    /* with 8 butterflies between each pair                         */

    for(sb=0;sb<sblim;sb++)
      for(ss=0;ss<8;ss++) {
        bu = xr[sb][17-ss];
        bd = xr[sb+1][ss];
        hybridIn[sb][17-ss] = (bu * aa->cs[ss]) - (bd * aa->ca[ss]);
        hybridIn[sb+1][ss] = (bd * aa->cs[ss]) + (bu * aa->ca[ss]);
      }

}

void initMdct(mdctData *md)
{
    int i;
    
    /* type 0 - normal window */
    for(i=0;i<36;i++)
        md->win[0][i] = sin( PI/36 *(i+0.5) );

    /* type 1 - start window */
    for(i=0;i<18;i++)
        md->win[1][i] = sin( PI/36 *(i+0.5) );
    for(i=18;i<24;i++)
        md->win[1][i] = 1.0;
    for(i=24;i<30;i++)
        md->win[1][i] = sin( PI/12 *(i+0.5-18) );
    for(i=30;i<36;i++)
        md->win[1][i] = 0.0;

    /* type 3 - stop window */
    for(i=0;i<6;i++)
        md->win[3][i] = 0.0;
    for(i=6;i<12;i++)
        md->win[3][i] = sin( PI/12 *(i+0.5-6) );
    for(i=12;i<18;i++) 
        md->win[3][i] =1.0;
    for(i=18;i<36;i++) 
        md->win[3][i] = sin( PI/36*(i+0.5) );

    /* type 2*/
    for(i=0;i<12;i++)
        md->win[2][i] = sin( PI/12*(i+0.5) ) ;
    for(i=12;i<36;i++)
        md->win[2][i] = 0.0 ;

    for (i=0; i<4*36; i++)
        md->COS[i] = cos(PI/(2*36) * i);
}

void inv_mdct(
              double in[18],
              double out[36],
              int block_type,
              mdctData *md )
{
    /*------------------------------------------------------------------*/
    /*                                                                  */
    /*    Function: Calculation of the inverse MDCT                     */
    /*    In the case of short blocks the 3 output vectors are already  */
    /*    overlapped and added in this modul.                           */
    /*                                                                  */
    /*    New layer3                                                    */
    /*                                                                  */
    /*------------------------------------------------------------------*/

    int     i, m, N, p;
    double  tmp[12],sum;

    for(i=0;i<36;i++)
        out[i]=0;
    
    if(block_type == 2 /* 2 */){
	 N=12;
        for(i=0;i<3;i++){
            for(p= 0;p<N;p++){
                sum = 0.0;
                for(m=0;m<N/2;m++)
                    sum += in[i+3*m] * cos( PI/(2*N)*(2*p+1+N/2)*(2*m+1));
                tmp[p] = sum * md->win[block_type][p] ;
            }
            for(p=0;p<N;p++) {
                out[6*i+p+6] += tmp[p];
	    }
        }
    }
    else{
        N=36;
        for(p= 0;p<N;p++){
            sum = 0.0;
            for(m=0;m<N/2;m++)
	    {
                sum += in[m] * md->COS[((2*p+1+N/2)*(2*m+1))%(4*36)];
	    }
            out[p] = sum * md->win[block_type][p];
        }
    }
}

void III_hybrid_init( double prevblck[2][SBLIMIT][SSLIMIT] )
{
        int i,j,k;

        for(i=0;i<2;i++)
          for(j=0;j<SBLIMIT;j++)
            for(k=0;k<SSLIMIT;k++)
              prevblck[i][j][k]=0.0;
}

void III_hybrid(
                double fsIn[SSLIMIT],   /* freq samples per subband in */
                double tsOut[SSLIMIT],  /* time samples per subband out */
                int sb,
                int ch,
                struct gr_info_s *gr_info,
                mdctData *md,
                double prevblck[2][SBLIMIT][SSLIMIT] )
{
    int ss;
    double rawout[36];
    int bt;


    bt = (gr_info->window_switching_flag && gr_info->mixed_block_flag &&
        (sb < 2)) ? 0 : gr_info->block_type;
    
    /* inverse mdct */
    inv_mdct( fsIn, rawout, bt, md);

    /* overlap addition */
    for(ss=0; ss<SSLIMIT; ss++) {
        tsOut[ss] = rawout[ss]+ prevblck[ch][sb][ss];
        prevblck[ch][sb][ss] = rawout[ss+18];
    }
}

