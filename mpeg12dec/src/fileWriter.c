HANDLE_fileWriter fileWriterInit(char *filename, FORMAT_fileWriter format, HANDLE_debug debug)
{
  HANDLE_fileWriter fw;
  
  debugEnter(debug, "fileWriterInit()");
  
  /* allocate handler struct */
  if ((fw = (HANDLE_fileWriter) malloc(sizeof(fileWriter_t))) == NULL)
  {
    debugPrintf(debug, D_ERROR, "Could not allocate memory for Handler");
    debugLeave(debug);
    return NULL;
  }
  
  fw->dbg = debug;
  fw->filename = filename;
  fw->initOutFile = 0;
  fw->format = format;
  if (format & FW_FORCE_MONO) 
    fw->outChannels = 1; 
  else if (format & FW_FORCE_STEREO) 
    fw->outChannels = 2;
  else
    fw->outChannels = 0;
  fw->infoPrinted = 0;
  fw->clipped = 0;
  
  debugLeave(debug);
  return fw;
}




ERROR_CODE_fileWriter fileWriterOutBuffer(HANDLE_fileWriter fw, HANDLE_pcmBuffer pcmBuffer)
{
  ERROR_CODE_fileWriter ret;
  STATUS_pcmBuffer  pcm;
  unsigned int      deliveredSamples  = pcmBufferGetAvailable(pcmBuffer);
  unsigned int      writtenSamples    = 0;
  unsigned int      channelsInBuf     = pcmBufferGetChannels(pcmBuffer);
  int               monoToStereo      = 0;
  int               stereoToMono      = 0;
  long              sample            = 0; 
  long              leftSample        = 0;
  int               i, leftChannel;
#ifdef USELIB_AFsp
  float             sampleOut;
  int               bits              = 24;
#else
  unsigned long     bigWord;
  int               bits              = (fw->format & FW_INT24)? 24 : 16;
  unsigned int      subwords          = bits / 8;
  unsigned char     *wordStart        = ((unsigned char*)&bigWord)+(4-subwords);  
  int               m;
#endif

  debugEnter(fw->dbg, "fileWriterOutBuffer()");
  
  /* Initialize out file */  
  if (!fw->initOutFile)
  {
    if (!fw->outChannels)
      fw->outChannels = channelsInBuf;
      
    if (!fw->samplingFreq)
      fw->samplingFreq = pcmBufferGetSamplingFreq(pcmBuffer);
      
    if (!initOutFile(fw))
    {
      debugPrintf (fw->dbg, D_ERROR, "Error while initializing output file");
      debugLeave (fw->dbg);
      return FW_INIT_ERROR;
    }
    fw->initOutFile = 1;
  }

  monoToStereo = ((fw->outChannels == 2) && (channelsInBuf == 1))?1:0;
  stereoToMono = ((fw->outChannels == 1) && (channelsInBuf == 2))?1:0;

  if ( fw->channelsBefore && channelsInBuf != fw->channelsBefore )
  {
    debugPrintf (fw->dbg, D_WARNING, "Implicit channel re-configuration from %d to %d", fw->channelsBefore, channelsInBuf);
  }
  fw->channelsBefore = channelsInBuf;
  
  if ( !fw->infoPrinted && stereoToMono )
  {
    debugPrintf (fw->dbg, D_WARNING, "Forcing mono! Channels will be mixed from stereo to mono");
    fw->infoPrinted = 1;
  }
  else
  if ( !fw->infoPrinted && monoToStereo )
  {
    debugPrintf (fw->dbg, D_WARNING, "Forcing stereo! Mono will be duplicated to stereo");
    fw->infoPrinted = 1;
  }
  
   
  
  leftChannel = 1;
  
  while (1) 
  {
    /* get next scaled and castet sample from pcm buffer */
    pcm = pcmBufferGetCasted(pcmBuffer, &sample, bits);
    if      (pcm == PCM_EMPTY)   break;         /* break if no sample available */
    else if (pcm == PCM_CLIPPED) fw->clipped++; /* count clipped samples */
    
    if (stereoToMono)
    {
      if (leftChannel)
      {
        leftSample  = sample;
        leftChannel = 0;
        continue; /* get right sample */
      }
      else
      {
        /* mean of two channels */
        sample      = (leftSample + sample) / 2;
        leftChannel = 1;
        deliveredSamples--;
      }
    }

#ifdef USELIB_AFsp

    /* write sample using AFsp-Lib */
    sampleOut = (float) sample/(1<<23);
    
    for (i=0; i<=monoToStereo; i++)
    {
      if (!AFfWriteData(fw->outFile, &sampleOut, 1)) break;
    }

#else /* USELIB_AFsp */

    /* convert sample to word written in big endian */
    bigWord = htonl(sample);

    /* write out words to file. break if no sample available */
    for (i=0; i<=monoToStereo; i++)
    {
      if (fwrite(wordStart, sizeof (char), subwords, fw->outFile) < subwords ) break;
    }
    
#endif /* USELIB_AFsp */
    
    writtenSamples++;

  } /* while(1) */
  
  fw->writtenSampleFrames += writtenSamples / channelsInBuf;
      
  if (writtenSamples != deliveredSamples)
  {
    debugPrintf (fw->dbg, D_ERROR, "Could only write %u from %u samples", writtenSamples, deliveredSamples);
    debugLeave (fw->dbg);
    return FW_WRITE_ERROR;
  }

  debugPrintf (fw->dbg, D_NOTICE_L2, "Successfully written %u samples", writtenSamples / channelsInBuf);
  debugLeave (fw->dbg);
  return FW_NO_ERROR;
}


void fileWriterClose(HANDLE_fileWriter fw)
{
  if (!fw) return;
  
  debugEnter (fw->dbg, "fileWriterClose()");

#ifndef USELIB_AFsp
  if (fw->format & FW_AIFF) 
  {
    IFF_AIFF pcm_aiff_data;
    
    pcm_aiff_data.numChannels       = fw->outChannels; /* TODO channelsInit ?? */
    pcm_aiff_data.numSampleFrames   = fw->writtenSampleFrames;
    if (fw->format & FW_INT24) 
    { 
      pcm_aiff_data.sampleSize      = 24; 
    } 
    else 
    { 
      pcm_aiff_data.sampleSize      = 16;
    } 
    pcm_aiff_data.sampleRate        = fw->samplingFreq;
    pcm_aiff_data.sampleType        = IFF_ID_SSND;
    pcm_aiff_data.blkAlgn.offset    = 0;
    pcm_aiff_data.blkAlgn.blockSize = 0;

    debugPrintf(fw->dbg, D_NOTICE_L2, "Writing AIFF header");
    if ( !aiff_write_headers(fw->outFile, &pcm_aiff_data)) 
    {
      debugPrintf(fw->dbg, D_ERROR, "Could not write AIFF headers");
    }
  }
#endif /* USELIB_AFsp */

  /* Close file */
#ifdef USELIB_AFsp
  if (fw->outFile) AFclose(fw->outFile);
#else
  if (fw->outFile) fclose(fw->outFile);
#endif

  if(fw->clipped > 0)
  { 
    debugPrintf(fw->dbg, D_NOTICE,"%d output samples clipped", fw->clipped);
  }

  debugLeave (fw->dbg);
}


