static
int initOutFile(HANDLE_fileWriter fw)
{

#ifdef USELIB_AFsp

  unsigned short     dFormat = 0;
  unsigned short     fType = 0;
  
  if (fw->format & FW_INT24) 
    dFormat = FD_INT24;
  else
    dFormat = FD_INT16;
    
  switch (fw->format & FW_FF_MASK)
  {
    case FW_RAW:
      fType = FTW_NH_EB;
      debugPrintf(fw->dbg, D_NOTICE_L2, "Opening RAW file");
      break;
    case FW_WAVE:
      fType = FTW_WAVE;
      debugPrintf(fw->dbg, D_NOTICE_L2, "Opening WAVE file");
      break;
    case FW_AIFF:
      fType = FTW_AIFF;
      debugPrintf(fw->dbg, D_NOTICE_L2, "Opening AIFF file");
      break;
    case FW_ESPS:
      /* TODO supported??? #ifdef ESPS ?? */
      break;
    default:
      debugPrintf(fw->dbg, D_WARNING, "No file format selected. Using WAVE format.");
      fType = FTW_WAVE;
      break;
  }
  
  /*  (AFoptions ())->ErrorHalt = 0;*/
  
  fw->outFile = AFopnWrite(fw->filename, fType, dFormat, fw->outChannels, fw->samplingFreq, NULL);
  if (fw->outFile == NULL ) 
  {
    debugPrintf(fw->dbg, D_ERROR, "Could not create '%s'", fw->filename);
    return 0;
  }

#else /* USELIB_AFsp */
  
  if ((fw->outFile = fopen(fw->filename, "w+b")) == NULL) 
  {
    debugPrintf(fw->dbg, D_ERROR, "Could not create '%s'", fw->filename);
    return 0;
  }

  if (fw->format & FW_AIFF)
  {
    if (!aiff_seek_to_sound_data(fw->outFile))
    {
      debugPrintf(fw->dbg, D_ERROR, "Could not seek to PCM sound data");
      return 0;
    }
  }

#ifdef ESPS
  if (fw->format & FW_ESPS)
  {
    debugPrintf(fw->dbg, D_NOTICE, "Writing ESPS header");
    esps_write_header(fw->outFile, (long) sampleFrames, (double) fw->samplingFreq, fw->outChannels, fw->filename );
  }
#endif /* ESPS */

#endif /* USELIB_AFsp */

  return 1;

} /* initOutFile() */







