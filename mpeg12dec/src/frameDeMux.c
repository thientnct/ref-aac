/**************************************************************************

  demux next frame in bitstream and output it into audioFrame buffer

*************************************************************************/
ERROR_CODE_frameDeMux frameDeMuxNext(HANDLE_frameDeMux fdm, HANDLE_bitBuffer audioFrame)
{
  ERROR_CODE_frameDeMux ret;
  ERROR_CODE_frameDeMux c_ret;
  
  debugEnter(fdm->debug, "frameDeMuxNext()");
  
  /* clean audio frame */
  bitBufferReset(audioFrame);

  /* set current frame as invalid */ 
  fdm->frameValid = 0;

  ret = checkCurrentFrame(fdm);
  if (ret != FMUX_NO_ERROR)
  {
    debugLeave(fdm->debug);
    return ret;
  }
  
  debugPrintf(fdm->debug, D_NOTICE_L2, "DeMuxing frame %ld at position %ld (%X)", fdm->frameCount, fdm->start, fdm->start);

  /* get audio data by layer */
  switch (fdm->frameData.lay)
  {
    case LAYER1:
    case LAYER2:
      /* Rewind bitstream buffer because header was read before */
      /* for layer1 and layer2: audioFrame and bitstreamFrame are the same, just copy it */
      bitBufferTransfer(fdm->bitstream, audioFrame, fdm->length);
      break;
      
    case LAYER3:
      {
        /* for layer3: the mainData of an audioFrame may be part of previous bitstreamFrames */
        unsigned long main_data_begin;
        unsigned long size_si, size_mdb, size_md, md_free, crc_size;
        long md_tomove, md_moved, md_avail;
        crc_size = (fdm->frameData.error_protection)?CRC_WORD_SIZE:0;
        
        /* Transfer header and CRC word into audio frame buffer */
        bitBufferTransfer(fdm->bitstream, audioFrame, HEADER_SIZE + crc_size);
        
        /* Get side info and main_data_begin size */
        size_si  = getSideInfoSize(&fdm->frameData);
        size_mdb = (fdm->frameData.version==MPEG_PHASE1)?9:8;
        
        /* Get pointer to beginning of mainData for this frame */
        main_data_begin = bitBufferGet(fdm->bitstream, size_mdb);
        debugPrintf(fdm->debug, D_NOTICE_L2, "Main data pointer: %d", main_data_begin);
        
        /* Write it into the audioFrame */
        bitBufferPut(audioFrame, main_data_begin, size_mdb);
  
        /* Transfer rest of side info from bitstream to audioFrame */
        bitBufferTransfer(fdm->bitstream, audioFrame, (size_si-size_mdb) );
        
        /* Refill mainDataBuffer with rest of frame data from bitstream */
        size_md = (fdm->length - size_si - HEADER_SIZE - crc_size);
        md_free = bitBufferGetFree(fdm->mainData);
        if (size_md > md_free)
        {
          debugPrintf(fdm->debug, D_WARNING, "Not enough space in main data buffer. Skipping %ld bits of recent main data.", size_md-md_free);
          bitBufferWind(fdm->mainData, size_md-md_free);
        }
        bitBufferTransfer(fdm->bitstream, fdm->mainData, size_md);
        debugPrintf(fdm->debug, D_NOTICE_L2, "Filled main data buffer with %ld bits. Current fill level is %.1f%%", size_md, (float)bitBufferGetAvailable(fdm->mainData)/(MAX_MAIN_DATA)*100 );
       
        /* Move read pointer to beginning of main data of current frame.
         * this may be data from last bitstream frame! */
        md_tomove = -(8*main_data_begin);
        md_moved = bitBufferWind(fdm->mainData, md_tomove);
        
        /* Check if enough main data was available in buffer to resolve backpointer */
        if (md_moved != md_tomove)
        {
          debugPrintf(fdm->debug, D_NOTICE_L2, "Not enough prebuffered main data to demux frame %d.", fdm->frameCount);
          bitBufferReset(audioFrame);
          /* Skip current main data: fast-forward main data buffer to end */
          bitBufferWind(fdm->mainData, bitBufferGetAvailable(fdm->mainData));
          ret = FMUX_NOT_ENOUGH_DATA;
        }
        else
        {
          /* Transfer main data from mainDataBuffer to audioFrame */
          md_avail = bitBufferGetAvailable(fdm->mainData);
          bitBufferTransfer(fdm->mainData, audioFrame, md_avail);
        }
      }
      break; /* LAYER3 */
  }
  
  c_ret = checkNextFrame(fdm);
  if (c_ret != FMUX_NO_ERROR)
  {
    bitBufferReset(audioFrame);
    debugLeave(fdm->debug);
    return c_ret;
  }
  
  /* set current frame as valid */ 
  if (ret == FMUX_NO_ERROR)
  {
    fdm->frameValid = 1;
  }
  fdm->frameCount++;
  
  debugPrintf(fdm->debug, D_NOTICE_L2, "Frame with length %ld demuxed.", fdm->length);
  debugLeave(fdm->debug);
  return ret;
}


/**
 * Get info about total amount of processed bits
 */
unsigned long frameDeMuxGotBits(HANDLE_frameDeMux fdm)
{
  return bitBufferGetRead(fdm->bitstream);
}

/**
 * Get info about last demuxed frame
 */
frameConfig frameDeMuxGetCurrentConfig(HANDLE_frameDeMux fdm)
{
  if (!fdm->frameValid)
  {
    debugPrintf(fdm->debug, D_WARNING, "Trying to read config of invalid frame.");
    fdm->frameConfig.length     = 0;
    fdm->frameConfig.samplerate = 0;
    fdm->frameConfig.bitrate    = 0;
    fdm->frameConfig.channels   = 0;
    fdm->frameConfig.version    = 0;
    fdm->frameConfig.layer      = 0;
  }
  return fdm->frameConfig;
}


/**
 * Free 
 */
void frameDeMuxFree(HANDLE_frameDeMux fdm)
{
  if (fdm)
  {
    bitBufferFree(fdm->mainData);
    free(fdm);
  }
}


