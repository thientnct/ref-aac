#define   SYNC_WORD         0xFFE00000
/* mask to sync complete header */
#define   SYNC_MASK         0xFFFE0000

/* mask and value to compare if free mode active */
#define   FREE_MASK         0x0000F000
#define   NO_SYNC_FOUND     (unsigned) -1
#define   HEADER_SIZE       32
#define   CRC_WORD_SIZE     16

/* max(main_data_pointer) * 8 = 2^9 * 8 = 4096 */
#define   MAX_MAIN_DATA 68640

typedef struct TAG_frameDeMux
{
  HANDLE_debug      debug;              /* debug handler */
  HANDLE_bitBuffer  bitstream;          /* input bitstream buffer */
  HANDLE_bitBuffer  mainData;           /* mainDataBuffer for layer3 */
  unsigned long     raw_header;         /* 32 bit header used by syncroutine */
  unsigned long     freeFrameSlots;     /* static frame size for free format */
  unsigned long     frameCount;         /* current frame number */
  unsigned long     start;              /* begining of next frame */
  unsigned long     length;             /* length of next frame */
  frameData         frameData;          /* frame data of next frame */
  frameConfig       frameConfig;        /* configuration of last demuxed frame */
  int               frameValid;         /* is the current frame valid? */
} frameDeMux_t;

/* 
 *  seek_sync_header(buf, header)
 *
 *  Syncronize to bitstream
 *  If *header == 0 seek only for syncword and get 32-bit header (this is
 *  used for first syncing to bitstream.)
 *  If *header != 0 syncronize to bitstream using known data from header
 *  (it is not sufficient to simply search for the 11 bit syncword because
 *  this pattern is often present in the bit stream.)
 *
 *  The function seeks for a byte aligned sync word in the bitstream and
 *  places the bitstream pointer right after the sync.
 *  It returns the sync position (beginning of syncword) if the sync was 
 *  found otherwise it returns NO_SYNC_FOUND.
 *
 *  This is not without problems, as
 *  1.  this pattern may also be emulated by the bit stream
 *  2.  it is not excluded by the standard to change the crc protection 
 *      from frame to frame.
 * 
 *  In free mode the frame size is determined by the distance between two
 *  syncwords. In that case do not print warnings! 
 */

/**
 * Seek for next syncword in bitstream
 */
static 
unsigned long seekSync (HANDLE_frameDeMux fdm)
{
  HANDLE_bitBuffer buf   = fdm->bitstream;
  unsigned long read;
  unsigned long align    = (8-(bitBufferGetRead(buf)%8))%8;
  unsigned long skipped  = 0; /* count skipped bits for warning */
  
  /* check if enough available data */
  if (bitBufferGetAvailable(buf) < HEADER_SIZE+align) return NO_SYNC_FOUND;
  
  /* align at first */
  bitBufferGet(buf, align);
  
  /* read 32 bits from bitstream */
  read = bitBufferGet(buf, HEADER_SIZE);
  
  while (bitBufferGetAvailable(buf) >= 8)
  {
    /* check syncword */
    if ( (read & SYNC_WORD) == SYNC_WORD )
    {
      /* syncword found */
      bitBufferWind(buf, -(HEADER_SIZE));
      debugPrintf(fdm->debug, D_DEBUG, "Sync found at: %X (skipped %lu bits)", bitBufferGetRead(buf)/8, skipped);
      return bitBufferGetRead(buf);
    }
      
    /* no syncword found, seek 1 byte foreward */
    read <<= 8;
    read |= bitBufferGet(buf, 8);
    skipped += 8;
  }
  
  /* no more data available in bit buffer */
  return NO_SYNC_FOUND;
}

static
unsigned int getFrameLength (HANDLE_frameDeMux fdm)
{
  HANDLE_bitBuffer buf = fdm->bitstream;
  frameData *fd        = &fdm->frameData;
  double bitsPerSlot   = fd->slotbits;
  int slots; /* frame size in slots */
  
  /* get frame size */
  if (fd->bitrate == 0) 
  {
    /* frame size for FREE FORMAT */
    if (fdm->freeFrameSlots == 0)
    {
      unsigned long header_1 = 0x0;
      unsigned long header_2 = 0x0;
      unsigned long next_sync_pos = 0;

      /* get first header */
      bitBufferGoTo(buf, fdm->start);
      header_1 = bitBufferGet(buf, HEADER_SIZE);
      
      /* search next header */
      while ((header_1 & SYNC_MASK) != (header_2 & SYNC_MASK))
      {
        next_sync_pos = seekSync(fdm); /* seek next sync */
        if (next_sync_pos == NO_SYNC_FOUND)
        {
           debugPrintf(fdm->debug, D_ERROR, "Free format indicated, but no second frame found.");
           return 0;
        }
        header_2 = bitBufferGet(buf, HEADER_SIZE);
      }

      /* go to beginning of sync-search */ 
      bitBufferGoTo(buf, fdm->start);

      fdm->freeFrameSlots = (next_sync_pos - fdm->start) / fd->slotbits;
      debugPrintf(fdm->debug, D_NOTICE_L1, "Free format indicated with %d slots per frame.", fdm->freeFrameSlots);
    }
    slots = fdm->freeFrameSlots;
  }    
  else
  {
    /* frame size calculation */
    double samplesPerFrame    = fd->samples;
    double samplingFrequency  = fd->sfreq;
    double bitRate            = fd->bitrate;
    
    /* Calc no of slots used for one bitstream frame. 
     * It is necessary to divide by bitsPerSlot to get right values (caused by rounding) */ 
    slots = (int)( (samplesPerFrame * bitRate)  / samplingFrequency / bitsPerSlot );
  }
  
  if (fd->padding) slots += 1;
  
  return slots * bitsPerSlot;  
}

static
unsigned int getSideInfoSize (frameData *frame)
{
  unsigned int size;
  int nch   = frame->channels;
  int mpeg1 = (frame->version==MPEG_PHASE1);
  int mode3 = (frame->mode==MPG_MD_MONO);
  
  /* side info bits               [ mpeg1   | mpeg2, 2.5 ]
     -----------------------------------------------------
        main_data_begin             9         8
        if (mode3)
          private_bits              5         1
        else
          private_bits              3         2
        scfsi                       0         1*nch*4
        
        (
          part2_3_length            12        12
          big_values                9         9
          global_gain               8         8
          scalfac_compress          4         9
          window_switching_flag     1         1
          if (window_switching_flag)
          {
            transfer block_type     2         2
            mixed_block_flag        1         1
            table_select            5*2       5*2
            subblock_gain           3*3       3*3
          }                       = 22      = 22
          else
          {
            table_select            5*3       5*3
            region0_count           4         4
            region1_count           3         3
          }                       = 22      = 22
          preflag                   0         1
          scalefac_scale            1         1
          couttable_slect           1         1
        )                         = 58        64
        * ngr                       2         1
                                  = 116       64
        * nch
  */
  
  if (mpeg1)
  {
    size  = 9;
    size += (mode3)? 5 : 3;
    size += 4 * nch;
    size += 59 * 2 * nch ;  /* gr = 2 */
  }
  else /* mpeg2, 2.5 */
  { 
    size  = 8;
    size += (mode3)? 1 : 2;
    size += 63 * nch ; /* gr = 1 */
  }
  
  return size;
}


static
ERROR_CODE_frameDeMux checkCurrentFrame(HANDLE_frameDeMux fdm)
{
  unsigned long expected_pos;
  unsigned long current_pos;
  unsigned long available, expected;

  /* check current bitstream position */
  expected_pos = fdm->start;
  current_pos  = bitBufferGetRead(fdm->bitstream);
  if (current_pos != expected_pos)
  {
    debugPrintf(fdm->debug, D_ERROR, "Internal error: bitstream isn't at right position! Difference: %ld bits.", (expected_pos - current_pos));
    debugLeave(fdm->debug);
    return FMUX_UNKNOWN_ERROR;
  } 
  
  /* check available data in bitstream */
  available = bitBufferGetAvailable(fdm->bitstream);
  expected  = fdm->length;
  if (expected == 0)
  {
    debugPrintf(fdm->debug, D_NOTICE_L2, "End of bitstream.");
    return FMUX_END_OF_STREAM;
  }
  else if (available < expected)
  {
    debugPrintf(fdm->debug, D_NOTICE_L2, "Not enough data at end of stream. Expected %lu bits, but %lu bits available.", expected, available);
    return FMUX_END_OF_STREAM;
  }

  fdm->frameConfig.length     = fdm->length;
  fdm->frameConfig.samplerate = fdm->frameData.sfreq * 1000;
  fdm->frameConfig.bitrate    = fdm->frameData.bitrate;
  fdm->frameConfig.channels   = fdm->frameData.channels;
  fdm->frameConfig.version    = fdm->frameData.version + 1;
  fdm->frameConfig.layer      = fdm->frameData.lay;
  
  if (fdm->frameConfig.bitrate == 0)
  {
    fdm->frameConfig.bitrate = fdm->frameConfig.samplerate / fdm->frameData.samples * fdm->length / 1000;
  }  
  
  return FMUX_NO_ERROR;
}


static
ERROR_CODE_frameDeMux checkNextFrame(HANDLE_frameDeMux fdm)
{
  ERROR_CODE_frameDeMux ret;
  unsigned long current_pos;

  /* next frame start position */
  fdm->start = fdm->start + fdm->length;
  fdm->length = 0;  
  
  /* check current bitstream position */
  current_pos = bitBufferGetRead(fdm->bitstream);
  if (current_pos != fdm->start)
  {
    /* IMPOSSIBLE current_pos must be at expected_sync_pos! */
    debugPrintf(fdm->debug, D_ERROR, "Internal error: bitstream isn't at right position! Difference: %ld bits.", (fdm->start - current_pos));
    return FMUX_UNKNOWN_ERROR;
  }
  
  /* check if more data available */
  if (bitBufferGetAvailable(fdm->bitstream) < HEADER_SIZE)
  {
    debugPrintf(fdm->debug, D_NOTICE_L2, "No more data in bitstream.");
    /* No next header, current frame is valid */
    return FMUX_NO_ERROR;
  }

  /* check next frame header */
  ret = FMUX_NO_ERROR;
  while (!getFrameData(&fdm->frameData, fdm->bitstream))
  {
    /* current frame does not ent with a valid new header -> do resync */
    unsigned long sync;
    
    debugPrintf(fdm->debug, D_NOTICE_L2, "Next frame header invalid. Searching new sync.");

    bitBufferReset(fdm->mainData); /* if an error occures the mainData is invalid! */
    
    /* back to frame start and move one bit foreward */
    bitBufferGoTo(fdm->bitstream, fdm->start - fdm->length + 1);

    /* search next sync */
    sync = seekSync(fdm);
    if (sync == NO_SYNC_FOUND)
    {
      current_pos = bitBufferGetRead(fdm->bitstream);
      debugPrintf(fdm->debug, D_WARNING, "Sync not found. Skipped %lu bits at end of bitstream.", current_pos-fdm->start);
      fdm->start = current_pos;
      return FMUX_INVALID_FRAME_LENGTH;
    }
    /* new frame starts at new sync position */
    fdm->start = sync;
    
    ret = FMUX_INVALID_FRAME_LENGTH; /* current frame is invalid */
  }

  bitBufferGoTo(fdm->bitstream, fdm->start);
  fdm->length = getFrameLength(fdm);
  return ret;
  
}


static
int seekFirstFrame(HANDLE_frameDeMux fdm)
{
  frameData frameDataNext;
  
  while (1)
  {
    fdm->start = seekSync(fdm);
    if (fdm->start == NO_SYNC_FOUND)
    {
      debugPrintf(fdm->debug, D_DEBUG, "No sync found.");
      return 0;
    }

    if (getFrameData(&fdm->frameData, fdm->bitstream))
    {
      /* first header valid, check next header */
      fdm->length = getFrameLength(fdm);
      bitBufferGoTo(fdm->bitstream, fdm->start + fdm->length);
      if (getFrameData(&frameDataNext, fdm->bitstream))
      {
        /* next header also valid, frame is valid */
       bitBufferGoTo(fdm->bitstream, fdm->start);
       return 1; 
      }
    }

    /* invalid header, search next sync */
    bitBufferGoTo(fdm->bitstream, fdm->start + 1);
    
  }
}


