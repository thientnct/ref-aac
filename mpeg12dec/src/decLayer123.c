static
int pcmBufferFill(HANDLE_pcmBuffer buf, decData *dd, int num)
{
  int             i,j,l;
  int             stereo = dd->frameData.channels;
  
  for (i = 0; i < num; i++) {          /* loop over samples per subband */
    for (j = 0; j < SBLIMIT; j++) {    /* loop over number of subbands */
      for (l = 0; l < stereo; l++) {   /* loop over number of channels */
        if ( pcmBufferPut(buf, dd->pcm_sample[l][i][j]) != PCM_OK )
          return 0;
      }  /* for (l = 0; l < stereo; l++) */
    }    /* for (j = 0; j < sblimit; j++) */
  }      /* for (i = 0; i < num; i++) */
  
  return 1;
}

